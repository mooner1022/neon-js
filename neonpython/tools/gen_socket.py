"""Generates neonpython's PySocketData.kt (the integer constants of _socket, _signal and select, the signals' names
glibc gives, the modules' docs) from what Linux CPython says: a JSON file of them, made by running this file's
DATA_SCRIPT with CPython 3.14 on Linux.

Usage, from the repository root:
    python3.14 -X utf8 -I -c "$(python -X utf8 -I neonpython/tools/gen_socket.py --script)" > data.json   (on Linux)
    python -X utf8 -I neonpython/tools/gen_socket.py data.json
"""
import json
import os
import sys

DATA_SCRIPT = r'''
import _socket, _signal, select, _posixsubprocess, json
def ints(m):
    return sorted((n, getattr(m, n)) for n in dir(m) if type(getattr(m, n)) is int)
out = {}
out['socket_ints'] = ints(_socket)
out['has_ipv6'] = _socket.has_ipv6
out['signal_ints'] = ints(_signal)
out['select_ints'] = [(n, v) for n, v in ints(select) if n == 'PIPE_BUF']
out['strsignal'] = [(i, _signal.strsignal(i)) for i in range(1, _signal.NSIG)]
out['valid_signals'] = sorted(_signal.valid_signals())
out['ignored'] = [i for i in sorted(_signal.valid_signals()) if _signal.getsignal(i) == _signal.SIG_IGN]
out['docs'] = {'_socket': _socket.__doc__, 'socket': _socket.socket.__doc__, 'select': select.__doc__,
               '_signal': _signal.__doc__, '_posixsubprocess': _posixsubprocess.__doc__}
print(json.dumps(out))
'''

TOOLS = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(TOOLS), 'src/main/kotlin/dev/mooner/neonpython/PySocketData.kt')


def kstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', '\\n') + '"'


def table(pairs):
    """name value lines as one string, cut in pieces of a source line each (a constant: the class's initializer stays small)."""
    items = [f'{n} {v}' for n, v in pairs]
    lines = []
    cur = ''
    for it in items:
        if cur and len(cur) + len(it) > 90:
            lines.append(cur)
            cur = ''
        cur += it + ';'
    if cur:
        lines.append(cur)
    return ' +\n        '.join(kstr(x) for x in lines)


def main(path):
    d = json.load(open(path, encoding='utf-8'))
    lines = []
    w = lines.append
    w('package dev.mooner.neonpython')
    w('')
    w('// Generated by neonpython/tools/gen_socket.py from Linux CPython 3.14.6: do not edit.')
    w('')
    w('/**')
    w(' * What _socket, _signal and select are given as Linux has them (Android\'s are the same): their integer constants')
    w(' * ("NAME value;" each), the signals glibc names (strsignal), those valid and those ignored at startup, the modules\'')
    w(' * docs.')
    w(' */')
    w('object PySocketData {')
    w('    /** _socket\'s integer constants (AF_*, SOCK_*, SOL_*, SO_*, IPPROTO_*, MSG_*, TCP_*...). */')
    w('    const val SOCKET_INTS = ' + table(d['socket_ints']))
    w('')
    w(f'    const val HAS_IPV6 = {"true" if d["has_ipv6"] else "false"}')
    w('')
    w('    /** _signal\'s integer constants (SIG*, NSIG, SIG_DFL, SIG_IGN, SIG_BLOCK..., ITIMER_*). */')
    w('    const val SIGNAL_INTS = ' + table(d['signal_ints']))
    w('')
    w('    /** select\'s (PIPE_BUF: poll, epoll and their constants are not given). */')
    w('    const val SELECT_INTS = ' + table(d['select_ints']))
    w('')
    w('    /** strsignal(n) for n from 1 (null: none, as for 32 and 33, glibc\'s own). */')
    w('    @JvmField val STRSIGNAL: Array<String?> = arrayOf(')
    for i, m in d['strsignal']:
        w(f'        {"null" if m is None else kstr(m)},')
    w('    )')
    w('')
    w('    /** signal.valid_signals(). */')
    w('    @JvmField val VALID_SIGNALS = intArrayOf(' + ', '.join(str(x) for x in d['valid_signals']) + ')')
    w('')
    w('    /** The signals ignored at startup (SIG_IGN: CPython ignores SIGPIPE and SIGXFSZ). */')
    w('    @JvmField val IGNORED_SIGNALS = intArrayOf(' + ', '.join(str(x) for x in d['ignored']) + ')')
    w('')
    for k, name in (('_socket', 'SOCKET_DOC'), ('socket', 'SOCKET_TYPE_DOC'), ('select', 'SELECT_DOC'),
                    ('_signal', 'SIGNAL_DOC'), ('_posixsubprocess', 'POSIXSUBPROCESS_DOC')):
        w(f'    const val {name} = {kstr(d["docs"][k])}')
    w('')
    w('    /** A table of [SOCKET_INTS]\'s form, each name with its value. */')
    w('    @JvmStatic')
    w('    fun ints(table: String): List<Pair<String, Long>> = table.split(\';\').filter { it.isNotEmpty() }.map {')
    w('        it.substringBefore(\' \') to it.substringAfter(\' \').toLong()')
    w('    }')
    w('}')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    if sys.argv[1:] == ['--script']:
        print(DATA_SCRIPT)
    else:
        main(sys.argv[1])
