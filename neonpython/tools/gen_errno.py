"""Generates neonpython's PyErrno.kt (the errno module, strerror's messages, posix's integer constants) from what
Linux CPython says: a JSON file of them, made by running this file's DATA_SCRIPT with CPython 3.14 on Linux.

Usage, from the repository root:
    python3.14 -X utf8 -I -c "$(python -X utf8 -I neonpython/tools/gen_errno.py --script)" > data.json   (on Linux)
    python -X utf8 -I neonpython/tools/gen_errno.py data.json
"""
import json
import os
import sys

DATA_SCRIPT = r'''
import errno, posix, os, json
out = {}
out['errno'] = sorted((n, getattr(errno, n)) for n in dir(errno) if n.startswith('E') and isinstance(getattr(errno, n), int))
out['errorcode'] = sorted(errno.errorcode.items())
out['strerror'] = [(i, os.strerror(i)) for i in range(0, 134)]
out['posix_ints'] = sorted((n, getattr(posix, n)) for n in dir(posix) if n.isupper() and isinstance(getattr(posix, n), int))
out['have_functions'] = list(posix._have_functions)
out['docs'] = {'errno': errno.__doc__, 'posix': posix.__doc__}
print(json.dumps(out))
'''

TOOLS = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(TOOLS), 'src/main/kotlin/dev/mooner/neonpython/PyErrno.kt')


def kstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', '\\n') + '"'


def main(path):
    d = json.load(open(path, encoding='utf-8'))
    lines = []
    w = lines.append
    w('package dev.mooner.neonpython')
    w('')
    w('// Generated by neonpython/tools/gen_errno.py from Linux CPython 3.14.6: do not edit.')
    w('')
    w('/**')
    w(' * errno as Linux has it (Android\'s are the same): its names and numbers, errno.errorcode, the messages')
    w(' * os.strerror gives (glibc\'s), and the integer constants of posix.')
    w(' */')
    w('object PyErrno {')
    for n, v in d['errno']:
        w(f'    const val {n} = {v}')
    w('')
    w('    /** errno\'s names, each with its number. */')
    w('    @JvmField val NAMES: Array<Pair<String, Int>> = arrayOf(')
    for n, v in d['errno']:
        w(f'        {kstr(n)} to {v},')
    w('    )')
    w('')
    w('    /** errno.errorcode: each number\'s name. */')
    w('    @JvmField val ERRORCODE: Map<Int, String> = mapOf(')
    for v, n in d['errorcode']:
        w(f'        {v} to {kstr(n)},')
    w('    )')
    w('')
    w('    private val MESSAGES = arrayOf(')
    for i, m in d['strerror']:
        w(f'        {kstr(m)},')
    w('    )')
    w('')
    w('    /** os.strerror(code): glibc\'s message. */')
    w('    @JvmStatic fun strerror(code: Int): String = if (code in MESSAGES.indices) MESSAGES[code] else "Unknown error $code"')
    w('')
    w('    /** posix\'s integer constants (O_*, F_OK, SEEK_*, WNOHANG...), each with its value. */')
    w('    @JvmField val POSIX_INTS: Array<Pair<String, Long>> = arrayOf(')
    for n, v in d['posix_ints']:
        w(f'        {kstr(n)} to {v}L,')
    w('    )')
    w('')
    w('    /** posix._have_functions: what posix\'s functions take (dir_fd, fd, follow_symlinks), Linux\'s list. */')
    w('    @JvmField val HAVE_FUNCTIONS: List<String> = listOf(' + ', '.join(kstr(x) for x in d['have_functions']) + ')')
    w('')
    w(f'    const val ERRNO_DOC = {kstr(d["docs"]["errno"])}')
    w(f'    const val POSIX_DOC = {kstr(d["docs"]["posix"])}')
    w('}')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    if sys.argv[1:] == ['--script']:
        print(DATA_SCRIPT)
    else:
        main(sys.argv[1])
