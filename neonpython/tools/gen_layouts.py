"""Generates neonpython's PyLayouts.kt: the layout CPython gives each of its C types (their __flags__,
__weakrefoffset__, __dictoffset__, __basicsize__ and __itemsize__), as Linux CPython 3.14 (64 bits) gives them. A
class's are worked out from its builtin base's (PySlots.layout), as CPython's type_new does.

Usage, from the repository root:
    python3.14 -X utf8 -I neonpython/tools/gen_layouts.py --dump > layouts.json   (CPython on Linux)
    python -X utf8 -I neonpython/tools/gen_layouts.py layouts.json
"""
import json
import os
import sys

# The C modules NeonPy has, and the pure modules whose C counterparts it has
MODULES = ['builtins', 'types', 'math', 'time', '_struct', 'posix', 'itertools', '_collections', 'collections', '_codecs',
           '_sre', 're', '_string', '_thread', '_weakref', 'weakref', 'gc', 'sys', '_operator', 'operator', '_imp',
           '_contextvars', 'contextvars', '_tokenize', '_random', '_sha2', '_md5', '_sha1', 'errno', 'binascii', 'zlib',
           'unicodedata', '_blake2', '_sha3', '_csv', '_socket', 'select', '_signal', '_posixsubprocess', 'atexit',
           'array', 'pyexpat', '_io', 'io', 'typing', '_typing', 'functools', '_functools', 'abc']

HEAPTYPE = 1 << 9

TOOLS = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(TOOLS), 'src/main/kotlin/dev/mooner/neonpython/PyLayouts.kt')

BS = chr(92)
NL = chr(10)


def c_type(t):
    """Whether [t] is a C type: a static one, or a heap one made from a spec (no class body, no Python methods)."""
    if not t.__flags__ & HEAPTYPE:
        return True
    d = vars(t)
    if '__firstlineno__' in d:
        return False
    import types
    return not any(isinstance(v, (types.FunctionType, classmethod, staticmethod, property)) for v in d.values())


def dump():
    import importlib
    seen = set()
    for mn in MODULES:
        try:
            m = importlib.import_module(mn)
        except ImportError:
            continue
        for v in vars(m).values():
            if isinstance(v, type):
                seen.add(v)
    # (the types no module names: iterators, views, descriptors' types...)
    work = [object]
    while work:
        t = work.pop()
        seen.add(t)
        try:
            subs = type.__subclasses__(t)
        except TypeError:
            continue
        work.extend(s for s in subs if s not in seen)
    out = {}
    for t in seen:
        if t.__module__ == '__main__' or not c_type(t):
            continue
        key = f'{t.__module__}.{t.__name__}'
        out[key] = [t.__flags__, t.__weakrefoffset__, t.__dictoffset__, t.__basicsize__, t.__itemsize__]
    print(json.dumps(out, sort_keys=True))


def kstr(s):
    return '"' + s.replace(BS, BS + BS).replace('"', BS + '"').replace('$', BS + '$').replace(NL, BS + 'n') + '"'


def gen(path):
    d = json.load(open(path, encoding='utf-8'))
    # (one string, read into the map when it is first asked for: a few hundred entries as code would be past what
    # the JIT compiles in a method, and many times the bytes)
    # (a type's name may have a space: 'symtable entry')
    rows = ['|'.join([k] + [str(x) for x in v]) for k, v in sorted(d.items())]
    chunks = []
    for i in range(0, len(rows), 40):
        chunks.append('        ' + kstr(NL.join(rows[i:i + 40]) + NL) + ' +')
    chunks[-1] = chunks[-1][:-2]
    lines = ['package dev.mooner.neonpython', '',
             '// Generated by neonpython/tools/gen_layouts.py from Linux CPython 3.14.6: do not edit.', '',
             '/**',
             ' * The layout of CPython\'s C types, by "module.name": their __flags__, __weakrefoffset__, __dictoffset__,',
             ' * __basicsize__ and __itemsize__ (copyreg, dataclasses and inspect read them; a class\'s are worked out from',
             ' * its builtin base\'s, PySlots.layout).',
             ' */',
             'object PyLayouts {',
             '    // (one row a type: its name and five numbers, by |)',
             '    private const val DATA =']
    lines += chunks
    lines += ['',
              '    @JvmField val MAP: Map<String, LongArray> = HashMap<String, LongArray>().also { m ->',
              "        for (row in DATA.split('" + BS + "n')) {",
              '            if (row.isEmpty()) continue',
              "            val f = row.split('|')",
              '            m[f[0]] = LongArray(5) { f[it + 1].toLong() }',
              '        }',
              '    }',
              '}']
    open(OUT, 'w', encoding='utf-8', newline=NL).write(NL.join(lines) + NL)
    print('wrote', OUT, len(d))


if __name__ == '__main__':
    if sys.argv[1:] == ['--dump']:
        dump()
    else:
        gen(sys.argv[1])
