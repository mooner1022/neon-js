"""Generates neonpython's PySignatures.kt: the __text_signature__ of each builtin function and method CPython's C modules
have (inspect.signature reads them), as Linux CPython 3.14 gives them.

Usage, from the repository root:
    python3.14 -X utf8 -I neonpython/tools/gen_signatures.py --dump > sigs.json   (CPython on Linux)
    python -X utf8 -I neonpython/tools/gen_signatures.py sigs.json
"""
import json
import os
import sys

# The C modules NeonPy has (its types' methods and its functions)
MODULES = ['builtins', 'math', 'time', '_struct', 'posix', 'itertools', '_collections', '_codecs', '_sre', '_string',
           '_thread', '_weakref', 'gc', 'sys', '_operator', '_imp', '_contextvars', '_tokenize', '_random', '_sha2',
           '_md5', '_sha1', 'errno', 'binascii', 'zlib', 'unicodedata', '_blake2', '_sha3', '_csv',
           '_socket', 'select', '_signal', '_posixsubprocess', 'atexit', 'array']

TOOLS = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(TOOLS), 'src/main/kotlin/dev/mooner/neonpython/PySignatures.kt')


def dump():
    import importlib
    out = {}
    for mn in MODULES:
        try:
            m = importlib.import_module(mn)
        except ImportError:
            continue
        for name, v in sorted(vars(m).items()):
            sig = getattr(v, '__text_signature__', None)
            if isinstance(v, type):
                for an, a in sorted(vars(v).items()):
                    s = getattr(a, '__text_signature__', None)
                    if isinstance(s, str):
                        out[f'{mn}.{v.__name__}.{an}'] = s
                if isinstance(sig, str):
                    out[f'{mn}.{v.__name__}'] = sig
            elif isinstance(sig, str) and callable(v):
                out[f'{mn}.{name}'] = sig
    print(json.dumps(out, sort_keys=True))


def kstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', '\\n') + '"'


def gen(path):
    d = json.load(open(path, encoding='utf-8'))
    lines = ['package dev.mooner.neonpython', '',
             '// Generated by neonpython/tools/gen_signatures.py from Linux CPython 3.14.6: do not edit.', '',
             '/**',
             ' * The __text_signature__ of CPython\'s builtin functions and methods, by "module.name" and',
             ' * "module.Type.name" (inspect.signature reads them).',
             ' */',
             'object PySignatures {']
    # (in chunks: a JVM method takes at most 64 KB of code)
    items = sorted(d.items())
    chunks = [items[i:i + 400] for i in range(0, len(items), 400)]
    for n, ch in enumerate(chunks):
        lines.append(f'    private fun part{n}(m: HashMap<String, String>) {{')
        for k, v in ch:
            lines.append(f'        m[{kstr(k)}] = {kstr(v)}')
        lines.append('    }')
    lines.append('')
    lines.append('    @JvmField val MAP: Map<String, String> = HashMap<String, String>().also { m ->')
    for n in range(len(chunks)):
        lines.append(f'        part{n}(m)')
    lines.append('    }')
    lines.append('}')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', OUT, len(d))


if __name__ == '__main__':
    if sys.argv[1:] == ['--dump']:
        dump()
    else:
        gen(sys.argv[1])
